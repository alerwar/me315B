basics = pl.scan_csv(
    "title.basics0.tsv.gz",
    separator="\t",
    null_values="\\N")

ratings = pl.scan_csv(
    "title.ratings.tsv.gz",
    separator="\t",
    null_values="\\N")

principals = pl.scan_csv(
    "title.principals0.tsv.gz",
    separator="\t",
    null_values="\\N")

print(basics.collect_schema())
print(ratings.collect_schema())
print(principals.collect_schema())

basics.head(5).collect()

ratings = ratings.with_columns(
    pl.col("averageRating").cast(pl.Float64),
    pl.col("numVotes").cast(pl.Int64))

filmes = (basics
    .filter(pl.col("titleType") == "movie")
    .join(ratings, on="tconst", how="inner"))
filmes.head(5).collect()

# ex1

resultado1 = ( filmes
    .select(
        "primaryTitle",
        "averageRating",
        "numVotes"
    )
    .sort(
        ["averageRating", "numVotes"],
        descending=[True, True]
    )
    .head(5)
    .collect())

resultado1

#ex2

resultado2 = (
    filmes
    .filter(pl.col("averageRating") > 8)
    .filter(pl.col("genres").is_not_null())
    .with_columns(
        pl.col("genres").str.split(",")
    )
    .explode("genres")
    .group_by("genres")
    .len()
    .sort("len", descending=True)
    .head(1)
    .collect())

resultado2

#ex3

resultado3 = ( principals
    .filter(
        pl.col("category").is_in(["actor", "actress"])
    )
    .join(
        filmes
        .filter(pl.col("averageRating") > 7.5)
        .select("tconst"),
        on="tconst",
        how="inner"
    )
    .select("nconst", "tconst")
    .unique()
    .group_by("nconst")
    .len()
    .sort("len", descending=True)
    .head(3)
    .collect())

resultado3

